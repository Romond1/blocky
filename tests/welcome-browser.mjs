import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
mkdirSync('output/welcome',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
try{
 await page.goto('http://127.0.0.1:5188/');
 await page.waitForFunction(()=>window.render_game_to_text);
 await page.waitForFunction(()=>document.querySelector('.welcome-video')?.readyState>=2);
 const read=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
 assert.equal((await read()).started,false);
 await page.waitForFunction(()=>!document.querySelector('.welcome-video').paused);
 const before=(await read()).player;
 await page.locator('#welcome-title').click();
 await page.keyboard.press('w');await page.keyboard.press('Space');await page.keyboard.press('e');
 await page.evaluate(()=>window.advanceTime(600));
 assert.deepEqual((await read()).player,before);
 const media=await page.locator('.welcome-video').evaluate(v=>({muted:v.muted,loop:v.loop,paused:v.paused,time:v.currentTime}));
 assert.equal(media.loop,true);assert.equal(media.muted,true);assert.equal(media.paused,false);
 await page.screenshot({path:'output/welcome/desktop.png'});
 await page.locator('.welcome-sound').click();assert.equal(await page.locator('.welcome-video').evaluate(v=>v.muted),false);
 await page.locator('.welcome-video').evaluate(v=>{v.currentTime=v.duration-.1;});
 await page.waitForFunction(()=>document.querySelector('.welcome-video')?.currentTime<2 && !document.querySelector('.welcome-video')?.paused);
 assert.equal((await read()).started,false);
 assert.equal(await page.locator('.welcome-video').evaluate(v=>v.ended),false);
 await page.locator('.welcome-hero[data-hero=yuki]').click();
 assert.equal(await page.locator('.welcome-hero[data-hero=yuki]').getAttribute('aria-pressed'),'true');
 await page.screenshot({path:'output/welcome/character-selection.png'});
 await page.keyboard.press('Enter');
 assert.equal((await read()).selectedHero,'yuki');
 assert.equal((await read()).ownershipValid,true);
 await page.keyboard.press('Tab');
 assert.equal((await read()).selectedHero,'mia');
 assert.equal((await read()).started,true);assert.equal(await page.locator('.welcome').isVisible(),false);
 assert.equal(await page.locator('.welcome-video').evaluate(v=>v.paused),true);
 await page.goto('http://127.0.0.1:5188/?choose=1');
 await page.setViewportSize({width:390,height:844});
 await page.locator('.welcome').waitFor();
 assert.equal(await page.locator('.hero-picker').count(),0);
 assert.equal(await page.locator('.welcome').evaluate(v=>v.scrollWidth<=v.clientWidth),true);
 await page.screenshot({path:'output/welcome/mobile.png',fullPage:true});
 await page.locator('.welcome-video').evaluate(v=>v.dispatchEvent(new Event('error')));
 assert.match(await page.locator('.welcome-video-status').textContent(),/could not load/);
 await page.locator('.welcome-hero[data-hero=mia]').click();
 await page.locator('.welcome-play').click();assert.equal((await read()).started,true);
 assert.equal((await read()).selectedHero,'mia');
 await page.goto('http://127.0.0.1:5188/');
 await page.locator('.welcome').waitFor();
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await page.locator('.welcome-play').evaluate(v=>getComputedStyle(v).animationName),'none');
 assert.deepEqual(errors,[]);
 console.log('PASS: looping autoplay, sound, frozen gameplay, actual loop restart, Enter starts selected Yuki, Tab switches to Mia, button starts selected Mia, media error, narrow layout and reduced motion.');
}finally{await browser.close();}
